import 'dart:convert';
import 'dart:typed_data';

import 'package:crypto/crypto.dart';

/// Turns the vendored Public Suffix List into the Dart table used by
/// `mail_trust`.
final class PublicSuffixGenerator {
  const PublicSuffixGenerator();

  static const input = 'tool/third_party/publicsuffix/public_suffix_list.dat';
  static const sums = 'tool/third_party/publicsuffix/SHA256SUMS';
  static const output =
      'packages/mail_trust/lib/src/generated/public_suffixes.g.dart';

  /// The Dart source for [list], whose SHA-256 must be [expectedSha256]
  /// (the reviewed file). Throws [FormatException] otherwise.
  String generate(Uint8List list, String expectedSha256) {
    final actual = sha256.convert(list).toString();
    if (actual != expectedSha256.trim().toLowerCase()) {
      throw FormatException('$input does not match $sums');
    }
    final rules = <String>{};
    for (final raw in utf8.decode(list).split('\n')) {
      final line = raw.trim();
      if (line.isEmpty || line.startsWith('//')) continue;
      // Rules end at the first whitespace.
      rules.add(line.split(RegExp(r'\s')).first.toLowerCase());
    }
    final sorted = rules.toList()..sort();
    final out = StringBuffer()
      ..writeln(
        '// GENERATED by tool/bin/generate_public_suffixes.dart; do not edit.',
      )
      ..writeln('//')
      ..writeln('// Data: the Public Suffix List, https://publicsuffix.org/')
      ..writeln(
        '// This Source Code Form is subject to the terms of the Mozilla Public',
      )
      ..writeln(
        '// License, v. 2.0. If a copy of the MPL was not distributed with this',
      )
      ..writeln('// file, You can obtain one at https://mozilla.org/MPL/2.0/.')
      ..writeln('// Source SHA-256: $actual')
      ..writeln()
      ..writeln(
        '/// Every rule: plain (`co.uk`), wildcard (`*.ck`) and exception',
      )
      ..writeln('/// (`!www.ck`), in lower case, Unicode labels as listed.')
      ..writeln('const Set<String> publicSuffixRules = {');
    for (final rule in sorted) {
      out.writeln(
        "  '${rule.replaceAll(r'\', r'\\').replaceAll("'", r"\'")}',",
      );
    }
    out.writeln('};');
    return out.toString();
  }

  /// The first checksum in a `SHA256SUMS` file.
  static String checksumFrom(String sumsFile) =>
      sumsFile.trim().split(RegExp(r'\s+')).first;
}
