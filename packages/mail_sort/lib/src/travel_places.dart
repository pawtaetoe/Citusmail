abstract final class TravelPlaces {
  /// The city an airport (IATA code) serves, or null.
  static String? cityOfAirport(String code) => _airports[code.toUpperCase()];

  /// Whether [code] is an airport the app knows.
  static bool isAirport(String code) =>
      _airports.containsKey(code.toUpperCase());

  /// The airline with IATA code [code] ("SQ"), or null.
  static String? airline(String code) => _airlines[code.toUpperCase()];

  /// A known city named in [text] ("Park Hotel Tokyo", "Kyoto Station"),
  /// the longest name first, or null.
  static String? cityIn(String text) {
    for (final (city, re) in _cityPatterns) {
      if (re.hasMatch(text)) return city;
    }
    return null;
  }

  static final _cityPatterns = [
    for (final c in ({
      ..._airports.values,
      ..._otherCities,
    }.toList()..sort((a, b) => b.length.compareTo(a.length))))
      (c, RegExp('\\b${RegExp.escape(c)}\\b', caseSensitive: false)),
  ];

