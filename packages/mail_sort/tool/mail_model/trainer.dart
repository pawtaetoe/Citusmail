/// Trains [MailModel] on the synthetic mail and writes its weights as a
/// Dart file. Deterministic: the same data and seed give the same file,
/// byte for byte (no `dart:math` `Random` or `exp`).
library;

import 'dart:convert';
import 'dart:math' as math;
import 'dart:typed_data';

import 'package:mail_sort/mail_sort.dart';

import 'rng.dart';
import 'synthetic_mail.dart';

/// Where the weights go, from the package's folder.
const generatedPath = 'lib/src/generated/mail_model_weights.g.dart';

/// How it learns.
const epochs = 14;
const learningRate = 0.4;
const l2 = 2e-6;

final class TrainedModel {
  TrainedModel(this.weights, this.scales, this.biases, this.examples);

  /// Bucket-major: [MailClass.values.length] per bucket.
  final Int8List weights;
  final Float64List scales;
  final Float64List biases;
  final int examples;
}

/// A softmax regression over [data], with AdaGrad and a little L2, the
/// classes weighted so that none dominates; then quantized to int8 with
/// a scale per class.
TrainedModel train(List<SynthMail> data, {int seed = trainingSeed}) {
  final k = MailClass.values.length;
  const buckets = MailModelFeatures.buckets;
  final xs = [for (final m in data) MailModelFeatures.of(m.sample)];
  final ys = [for (final m in data) m.label.index];
  final counts = List.filled(k, 0);
  for (final y in ys) {
    counts[y]++;
  }
  final classWeight = [
    for (final n in counts) n == 0 ? 0.0 : math.sqrt(data.length / (k * n)),
  ];
  final w = Float64List(buckets * k);
  final g = Float64List(buckets * k);
  final bias = Float64List(k);
  final gBias = Float64List(k);
  final z = Float64List(k);
  const eps = 1e-8;
  final r = Rng(seed);
  final order = List.generate(data.length, (i) => i);
  for (var epoch = 0; epoch < epochs; epoch++) {
    for (final i in r.shuffled(order)) {
      final x = xs[i];
      for (var c = 0; c < k; c++) {
        z[c] = bias[c];
      }
      for (var j = 0; j < x.length; j++) {
        final base = x.buckets[j] * k;
        final v = x.values[j];
        for (var c = 0; c < k; c++) {
          z[c] += v * w[base + c];
        }
      }
      var max = z[0];
      for (var c = 1; c < k; c++) {
        if (z[c] > max) max = z[c];
      }
      var sum = 0.0;
      for (var c = 0; c < k; c++) {
        z[c] = exactExp(z[c] - max);
        sum += z[c];
      }
      final cw = classWeight[ys[i]];
      for (var c = 0; c < k; c++) {
        // The gradient of the loss in each class's score.
        z[c] = cw * (z[c] / sum - (c == ys[i] ? 1 : 0));
      }
      for (var j = 0; j < x.length; j++) {
        final base = x.buckets[j] * k;
        final v = x.values[j];
        for (var c = 0; c < k; c++) {
          final at = base + c;
          final grad = z[c] * v + l2 * w[at];
          g[at] += grad * grad;
          w[at] -= learningRate * grad / math.sqrt(g[at] + eps);
        }
      }
      for (var c = 0; c < k; c++) {
        gBias[c] += z[c] * z[c];
        bias[c] -= learningRate * z[c] / math.sqrt(gBias[c] + eps);
      }
    }
  }
  final scales = Float64List(k);
  for (var c = 0; c < k; c++) {
    var max = 0.0;
    for (var b = 0; b < buckets; b++) {
      final v = w[b * k + c].abs();
      if (v > max) max = v;
    }
    scales[c] = _round(max == 0 ? 1 : max / 127);
  }
  final q = Int8List(buckets * k);
  for (var b = 0; b < buckets; b++) {
    for (var c = 0; c < k; c++) {
      q[b * k + c] = (w[b * k + c] / scales[c]).round().clamp(-127, 127);
    }
  }
  return TrainedModel(
    q,
    scales,
    Float64List.fromList([for (final v in bias) _round(v)]),
    data.length,
  );
}

/// [v] as it is written in the generated file, and so read back.
double _round(double v) => double.parse(v.toStringAsPrecision(9));

/// The generated Dart file for [model].
String generatedSource(TrainedModel model, {int seed = trainingSeed}) {
  final bytes = MailModel.encodeWeights(
    model.weights,
    buckets: MailModelFeatures.buckets,
    classes: MailClass.values.length,
  );
  final encoded = base64.encode(bytes);
  const chunk = 72;
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/train_mail_model.dart; do not edit.')
    ..writeln('//')
    ..writeln(
      '// Trained on ${model.examples} synthetic emails '
      '(tool/mail_model/), seed $seed:',
    )
    ..writeln("// made up, never anyone's real mail.")
    ..writeln(
      '// This Source Code Form is subject to the terms of the Mozilla Public',
    )
    ..writeln(
      '// License, v. 2.0. If a copy of the MPL was not distributed with this',
    )
    ..writeln('// file, You can obtain one at https://mozilla.org/MPL/2.0/.')
    ..writeln()
    ..writeln('/// The features the weights are for ([MailModelFeatures]).')
    ..writeln('const mailModelFeatureVersion = ${MailModelFeatures.version};')
    ..writeln('const mailModelBuckets = ${MailModelFeatures.buckets};')
    ..writeln()
    ..writeln('/// The classes, in the order of the weights.')
    ..writeln('const mailModelClasses = [');
  for (final c in MailClass.values) {
    out.writeln("  '${c.name}',");
  }
  out
    ..writeln('];')
    ..writeln()
    ..writeln('/// Each class\'s bias.')
    ..writeln('const mailModelBiases = <double>[');
  for (final v in model.biases) {
    out.writeln('  ${v.toStringAsPrecision(9)},');
  }
  out
    ..writeln('];')
    ..writeln()
    ..writeln('/// Each class\'s weight per unit of int8.')
    ..writeln('const mailModelScales = <double>[');
  for (final v in model.scales) {
    out.writeln('  ${v.toStringAsPrecision(9)},');
  }
  out
    ..writeln('];')
    ..writeln()
    ..writeln(
      '/// Base64: a bitmap of the buckets with weights, then one signed',
    )
    ..writeln('/// byte per class for each (${bytes.length} bytes).')
    ..writeln('const mailModelWeights = [');
  for (var i = 0; i < encoded.length; i += chunk) {
    final end = math.min(i + chunk, encoded.length);
    out.writeln("  '${encoded.substring(i, end)}',");
  }
  out.writeln('];');
  return out.toString();
}

/// Trains on the synthetic mail and gives the generated file.
String trainAndGenerate() => generatedSource(train(syntheticMail()));
